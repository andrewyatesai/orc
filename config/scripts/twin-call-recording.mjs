// The recording half of `pnpm parity:twin-derived` (see
// twin-test-derived-parity-cases.mjs for what the recording is FOR).
//
// Everything here writes generated code and then runs it under vitest:
//   * a RECORDER per twin — same directory as the twin so the twin's own
//     relative imports still resolve — re-exporting it untouched except that the
//     ported functions are wrapped to log (args, result);
//   * a resolver PLUGIN that redirects any relative import landing on a twin to
//     that twin's recorder. Vitest cannot alias by resolved path, and the
//     recorder's own import must be exempt or the wrapper calls itself;
//   * a REPLAY test that drives every existing vector case through the module's
//     parity adapter, which is how the argument and output encodings get
//     measured instead of assumed.
//
// The recorders land inside `src/`, so every path out of here — normal return,
// throw, SIGINT — deletes them.

import { spawnSync } from 'node:child_process'
import { createRequire } from 'node:module'
import fs from 'node:fs'
import path from 'node:path'

const require = createRequire(import.meta.url)
const RECORDER_SUFFIX = '.__twin-recorder.ts'

const created = new Set()

export function cleanupRecorders() {
  for (const file of created) {
    fs.rmSync(file, { force: true })
  }
  created.clear()
}

process.on('exit', cleanupRecorders)
for (const signal of ['SIGINT', 'SIGTERM']) {
  process.on(signal, () => {
    cleanupRecorders()
    process.exit(1)
  })
}

function writeSink(paths) {
  fs.writeFileSync(
    path.join(paths.workDir, 'record-sink.mjs'),
    `// GENERATED. One JSON line per twin call. \`replay\` tags the phase-A calls
// the adapter makes over the existing corpus, which is what teaches the driver
// how a module encodes its arguments.
import { appendFileSync } from 'node:fs'

const SINK = ${JSON.stringify(paths.sinkFile)}

export function recordTwinCall(module, fn, args, result) {
  let testName = null
  try {
    // Names the test that produced the case, so a divergence reads as a
    // behaviour ("keeps a native OpenCode title"), not as an opaque input.
    testName = globalThis.expect?.getState?.()?.currentTestName ?? null
  } catch {
    testName = null
  }
  const replay = globalThis.__TWIN_REPLAY__ ?? null
  try {
    appendFileSync(SINK, \`\${JSON.stringify({ module, fn, args, result, testName, replay })}\\n\`)
  } catch {
    // A non-serializable argument is a case this instrument cannot carry; the
    // gap shows up as calls-minus-cases, never as a fabricated case.
  }
}
`
  )
}

export function writeRecorder(paths, moduleName, functions, twinPath) {
  const base = `./${path.basename(twinPath).replace(/\.ts$/, '')}`
  const relative = path.relative(
    path.dirname(twinPath),
    path.join(paths.workDir, 'record-sink.mjs')
  )
  const sink = relative.startsWith('.') ? relative : `./${relative}`
  const lines = [
    '// GENERATED by config/scripts/twin-call-recording.mjs — deleted on exit.',
    `import * as twin from '${base}'`,
    `import { recordTwinCall } from '${sink}'`,
    `export * from '${base}'`,
    ''
  ]
  for (const fn of functions) {
    lines.push(
      `export const ${fn} = (...args) => {`,
      `  const result = twin.${fn}(...args)`,
      `  recordTwinCall(${JSON.stringify(moduleName)}, ${JSON.stringify(fn)}, args, result)`,
      '  return result',
      '}'
    )
  }
  const recorderPath = twinPath.replace(/\.ts$/, RECORDER_SUFFIX)
  fs.writeFileSync(recorderPath, `${lines.join('\n')}\n`)
  created.add(recorderPath)
  return recorderPath
}

/** Phase A: drive every existing vector case through the module's own parity
 *  adapter, with the recorder underneath, to observe how a vector `input`
 *  becomes positional arguments and how a twin's raw return becomes the answer
 *  the corpus records. */
function writeReplayTest(paths, eligible) {
  const replayPath = path.join(paths.workDir, 'convention-replay.test.mjs')
  const lines = [
    '// GENERATED by config/scripts/twin-call-recording.mjs.',
    "import { appendFileSync } from 'node:fs'",
    "import { describe, it } from 'vitest'",
    `const ADAPTER_SINK = ${JSON.stringify(paths.adapterSinkFile)}`,
    ''
  ]
  for (const [index, moduleInfo] of eligible.entries()) {
    lines.push(
      `import { dispatch as dispatch${index} } from ${JSON.stringify(moduleInfo.adapterPath)}`
    )
  }
  lines.push('', 'const MODULES = [')
  for (const [index, moduleInfo] of eligible.entries()) {
    const cases = JSON.stringify(
      moduleInfo.cases.map((c) => ({ function: c.function, input: c.input }))
    )
    lines.push(
      `  { module: ${JSON.stringify(moduleInfo.module)}, dispatch: dispatch${index}, cases: ${cases} },`
    )
  }
  lines.push(
    ']',
    '',
    "describe('convention replay', () => {",
    '  for (const entry of MODULES) {',
    '    it(entry.module, () => {',
    '      for (const [caseIndex, testCase] of entry.cases.entries()) {',
    '        globalThis.__TWIN_REPLAY__ = { caseIndex, input: testCase.input }',
    '        try {',
    '          const output = entry.dispatch(testCase.function, testCase.input)',
    '          const row = { module: entry.module, fn: testCase.function, caseIndex, output }',
    '          appendFileSync(ADAPTER_SINK, `${JSON.stringify(row)}\\n`)',
    '        } catch {',
    '          // A vector that throws still reached the twin with real arguments,',
    '          // and that is all phase A needs.',
    '        } finally {',
    '          globalThis.__TWIN_REPLAY__ = null',
    '        }',
    '      }',
    '    })',
    '  }',
    '})',
    ''
  )
  fs.writeFileSync(replayPath, lines.join('\n'))
  return replayPath
}

function writeVitestConfig(paths, redirects, testFiles) {
  const configPath = path.join(paths.workDir, 'vitest.twin-recorder.config.mjs')
  fs.writeFileSync(
    configPath,
    `// GENERATED by config/scripts/twin-call-recording.mjs.
import path from 'node:path'
import { defineConfig } from 'vitest/config'

const REDIRECTS = new Map(${JSON.stringify([...redirects], null, 2)})

export default defineConfig({
  plugins: [
    {
      name: 'twin-recorder-redirect',
      enforce: 'pre',
      resolveId(source, importer) {
        if (!importer || !source.startsWith('.')) {
          return null
        }
        const resolved = path.resolve(path.dirname(importer), source)
        for (const suffix of ['', '.ts', '.tsx', '/index.ts']) {
          const recorder = REDIRECTS.get(resolved + suffix)
          // Exempt the recorder's own import, or the wrapper calls itself.
          if (recorder && importer !== recorder) {
            return recorder
          }
        }
        return null
      }
    }
  ],
  test: {
    globals: true,
    environment: 'node',
    include: ${JSON.stringify(testFiles)},
    reporters: ['dot'],
    passWithNoTests: true
  }
})
`
  )
  return configPath
}

/** Claim the work dir, refusing rather than stomping a run already in it.
 *
 *  The unconditional `rm -rf` this replaces destroyed a concurrent run's
 *  generated replay test, config and sink mid-flight, and the victim did not
 *  crash — it reported "0 replay calls", every function UNDERIVABLE, "0 modules
 *  produced cases". That reads as "the tool found nothing", which is the same
 *  shape as a clean result. A stale lock from a killed run is cleared by
 *  deleting the directory. */
export function prepareWorkDir(paths) {
  const lock = path.join(paths.workDir, 'run.lock')
  if (fs.existsSync(lock)) {
    const owner = fs.readFileSync(lock, 'utf8').trim()
    throw new Error(
      `${paths.workDir} is in use by pid ${owner}. Two runs cannot share it — the ` +
        "second would delete the first's generated files and report an empty, " +
        `clean-looking result. Wait for it, or remove ${paths.workDir} if that pid is gone.`
    )
  }
  fs.rmSync(paths.workDir, { recursive: true, force: true })
  fs.mkdirSync(paths.candidateDir, { recursive: true })
  fs.writeFileSync(lock, String(process.pid))
  fs.writeFileSync(paths.sinkFile, '')
  writeSink(paths)
  const release = () => fs.rmSync(lock, { force: true })
  process.on('exit', release)
}

/** Run the twin test files plus the replay under the redirect plugin, then
 *  return every recorded call.
 *
 *  A red twin test still made every call it made before failing, and those calls
 *  are as real as any other, so the exit status is reported and not obeyed. */
export function runRecording(paths, { repoRoot, redirects, testFiles, eligible }) {
  const replayPath = writeReplayTest(paths, eligible)
  const configPath = writeVitestConfig(paths, redirects, [
    path.relative(repoRoot, replayPath),
    ...testFiles
  ])
  const vitestCli = path.join(path.dirname(require.resolve('vitest/package.json')), 'vitest.mjs')
  const run = spawnSync(process.execPath, [vitestCli, 'run', '--config', configPath], {
    cwd: repoRoot,
    stdio: ['ignore', 'pipe', 'pipe'],
    encoding: 'utf8',
    maxBuffer: 256 * 1024 * 1024,
    env: { ...process.env, CI: '1' }
  })
  cleanupRecorders()

  const readLines = (file) =>
    fs.existsSync(file)
      ? fs
          .readFileSync(file, 'utf8')
          .split('\n')
          .filter(Boolean)
          .map((line) => JSON.parse(line))
      : []

  return {
    status: run.status,
    calls: readLines(paths.sinkFile),
    adapterOutputs: readLines(paths.adapterSinkFile)
  }
}
